import { chromium } from '@playwright/test';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const origin = process.env.REVIEW_ORIGIN || 'http://127.0.0.1:3000';
const output = 'artifacts/review/batch-1/hygiene.json';
const prohibited = /simulat|synthetic|stub|placeholder|mock|\bTODO\b|\bFIXME\b|lorem|coming soon|in progress|foundation|exhibition|legacy|\bdemo\b|context pack|readiness|still being built|NDP III|Classified/ig;
const failures = [];
const checked = [];
function scan(where, content) {
  const matches = [...content.matchAll(prohibited)].map(m => m[0]);
  if (matches.length) failures.push({ where, matches: [...new Set(matches)] });
  checked.push(where);
}
async function scanDocs(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) await scanDocs(filename);
    else if (/\.(md|html|json|txt|ya?ml)$/.test(entry.name)) scan(filename, await readFile(filename, 'utf8'));
  }
}
await scanDocs('docs');
scan('README.md', await readFile('README.md', 'utf8'));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext();
const page = await context.newPage();
page.on('pageerror', error => failures.push({ where: page.url(), error: error.message }));
const queue = ['/'];
const visited = new Set();
while (queue.length) {
  const pathname = queue.shift();
  if (visited.has(pathname)) continue;
  visited.add(pathname);
  const response = await page.goto(origin + pathname, { waitUntil: 'networkidle' });
  if (response.status() !== 200) failures.push({ where: pathname, status: response.status() });
  const title = await page.title();
  if (!title) failures.push({ where: pathname, error: 'Missing title' });
  scan(`${pathname} rendered text and metadata`, `${title}\n${await page.locator('body').innerText()}\n${await page.locator('meta[name="description"]').getAttribute('content') || ''}`);
  // Inspect HTML generated by the production build, excluding implementation scripts/styles.
  scan(`${pathname} HTML`, await page.locator('body').evaluate(element => { const copy = element.cloneNode(true); copy.querySelectorAll('script,style').forEach(e => e.remove()); return copy.innerHTML; }));
  const links = await page.locator('a[href]').evaluateAll(anchors => anchors.map(a => a.getAttribute('href')));
  for (const href of links) {
    if (!href || href.startsWith('mailto:') || href.startsWith('tel:')) continue;
    const url = new URL(href, origin + pathname);
    if (url.origin !== new URL(origin).origin) continue;
    if (url.hash && url.pathname === pathname) {
      if (await page.locator(`[id="${url.hash.slice(1)}"]`).count() === 0) failures.push({ where: pathname, deadAnchor: href });
    } else queue.push(url.pathname);
  }
}
for (const pathname of ['/showcase','/data-audit.html','/context','/design','/api/briefing']) {
  const response = await context.request.get(origin + pathname);
  if (response.status() !== 404 && response.status() !== 410) failures.push({ where: pathname, error: 'Retired route still responds', status: response.status() });
  checked.push(`removed ${pathname}`);
}
await browser.close();
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, JSON.stringify({ date: '2026-11-23', origin, checked, routes: [...visited], failures, passed: failures.length === 0 }, null, 2));
console.log(JSON.stringify({ checks: checked.length, routes: [...visited], failures, passed: failures.length === 0 }, null, 2));
if (failures.length) process.exit(1);
